import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { format } from "prettier";

const root = resolve(import.meta.dirname, "../../..");
const manifestPath = resolve(root, "runtime/manifest.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const files = {};
for (const relativePath of manifest.files) {
  files[relativePath] = await readFile(resolve(root, "runtime", relativePath), "utf8");
}
const contentHash = createHash("sha256");
for (const relativePath of manifest.files) {
  contentHash.update(relativePath);
  contentHash.update("\0");
  contentHash.update(files[relativePath]);
  contentHash.update("\0");
}
const expectedHash = contentHash.digest("hex");
if (process.argv.includes("--check")) {
  if (manifest.contentHash !== expectedHash) {
    throw new Error("Trace runtime manifest is stale; build @trace/shared to regenerate it");
  }
} else if (manifest.contentHash !== expectedHash) {
  manifest.contentHash = expectedHash;
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}
const source =
  `// Generated by scripts/generate-trace-runtime.mjs.\n` +
  `export const BUNDLED_TRACE_RUNTIME_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n` +
  `export const BUNDLED_TRACE_RUNTIME_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};\n`;
await writeFile(
  resolve(root, "packages/shared/src/trace-runtime.generated.ts"),
  await format(source, { parser: "typescript" }),
);
