import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const manifest = JSON.parse(await readFile(resolve(root, "runtime/manifest.json"), "utf8"));
const files = {};
for (const relativePath of manifest.files) {
  files[relativePath] = await readFile(resolve(root, "runtime", relativePath), "utf8");
}
await writeFile(
  resolve(root, "packages/shared/src/trace-runtime.generated.ts"),
  `// Generated by scripts/generate-trace-runtime.mjs.\n` +
    `export const BUNDLED_TRACE_RUNTIME_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n` +
    `export const BUNDLED_TRACE_RUNTIME_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};\n`,
);
